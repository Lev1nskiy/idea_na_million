"""Детерминированные шаблоны ответов (без LLM).

Тон — по Ст. 7: вежливо, эмпатично, без признания юридической вины и без споров.
Числа (SLA, %) подставляются из Policy/ToolFacts на момент вызова — в тексте
шаблонов жёстких чисел нет (Ст. 2).
"""
from __future__ import annotations

from collections.abc import Sequence

from core.schemas import SlaInfo

REMEDY_LABELS = {"replacement": "замена", "discount": "скидка", "bonus": "бонус"}


def remedy_labels(options: Sequence[str]) -> list[str]:
    """Русские названия remedy-опций из Policy (неизвестные — как есть)."""
    return [REMEDY_LABELS.get(option, option) for option in options]


def _join_or(items: Sequence[str]) -> str:
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " или " + items[-1]


def remedy_orientation(remedies: Sequence[str]) -> str:
    """Remedy-опции как ориентир, без обязательств (Ст. 6)."""
    if not remedies:
        return ""
    return (
        f"Как ориентир: возможные варианты решения — {_join_or(remedies)}; "
        "окончательное решение примет менеджер."
    )


def _hours_phrase(hours: int) -> str:
    """«2 часов» нельзя: в течение 1 часа / 2 часов / 5 часов / 21 часа."""
    word = "часа" if hours % 10 == 1 and hours % 100 != 11 else "часов"
    return f"{hours} {word}"


def _pct(value: float) -> str:
    return f"{value:g}"


def sla_phrase(sla: SlaInfo) -> str:
    """Честный срок связи с менеджером (Ст. 6, 8) с учётом рабочего времени."""
    if sla.response_hours <= 0:
        return "Менеджер подключится, как только освободится."
    period = f"в течение {_hours_phrase(sla.response_hours)}"
    if sla.is_work_time:
        return f"Менеджер подключится к диалогу {period}."
    return f"Сейчас нерабочее время, поэтому менеджер ответит {period}."


def f_script(has_legit_part: bool = False) -> str:
    """Категория F (Ст. 3): ответ на попытку манипуляции."""
    text = (
        "Я не могу выполнять инструкции, которые меняют правила работы, — "
        "я действую строго в рамках правил компании. "
        "С радостью помогу с вопросами о товарах, заказах, доставке и гарантии."
    )
    if has_legit_part:
        text += " Обычный вопрос из вашего сообщения я обработаю следующим сообщением."
    return text


def ack_dispute(sla: SlaInfo, remedies: Sequence[str] = ()) -> str:
    """Категория I, фаза ACKNOWLEDGE (Ст. 6): признать проблему, не признавая вины."""
    parts = [
        "Я вижу, что вопрос сложный и требует участия специалиста.",
        "Приношу извинения за доставленные неудобства — мне важно, чтобы вы остались довольны.",
        "Я уже передал информацию менеджеру.",
        sla_phrase(sla),
        remedy_orientation(remedies),
        "Если хотите, расскажите подробности — я зафиксирую их для менеджера.",
    ]
    return " ".join(p for p in parts if p)


def smooth_fallback(sla_phrase_text: str, remedies: Sequence[str] = ()) -> str:
    """Фаза SMOOTH без LLM: эмпатия + честный срок + remedy как ориентир."""
    parts = [
        "Понимаю, как это важно для вас, и приношу извинения за доставленные неудобства.",
        "Я добавил ваше сообщение к обращению — менеджер увидит его сразу.",
        sla_phrase_text,
        remedy_orientation(remedies),
    ]
    return " ".join(p for p in parts if p)


def hold_ping(sla: SlaInfo, remedies: Sequence[str] = ()) -> str:
    """Периодическое сообщение в фазе HOLD: клиента не оставляют в тишине (Ст. 6, 9)."""
    parts = [
        "Я на связи: ваше обращение передано менеджеру.",
        sla_phrase(sla),
        remedy_orientation(remedies),
        "Если появятся новые детали — напишите, я добавлю их к обращению.",
    ]
    return " ".join(p for p in parts if p)


def interim_ack() -> str:
    """Промежуточный ответ, если пайплайн не уложился в 3.5 с (Ст. 9)."""
    return "Принял ваше сообщение, уточняю детали — вернусь с ответом в ближайшее время."


def discount_offer(max_pct: float) -> str:
    """Первое (и единственное) предложение максимума по политике (Ст. 6, граница C/I)."""
    return (
        "Максимальная скидка, которую я могу оформить для вашего заказа по действующей "
        f"политике компании, — {_pct(max_pct)}%. Оформить предложение с такой скидкой?"
    )


def discount_limit_confirm(max_pct: float) -> str:
    """Повторное настаивание: вежливо подтверждаем лимит, новых предложений не делаем."""
    return (
        "Понимаю ваше желание получить лучшие условия. К сожалению, в рамках действующей "
        f"политики компании максимальная скидка для вашего заказа — {_pct(max_pct)}%. "
        "Её я могу оформить сразу."
    )


def discount_none() -> str:
    """По действующей политике скидка для такого заказа не предусмотрена."""
    return (
        "По действующей политике компании для заказа такой суммы скидка не предусмотрена. "
        "Если вы рассмотрите комплект или увеличите заказ, я пересчитаю условия."
    )


def ask_order_details() -> str:
    """Для расчёта скидки нужна позиция и количество."""
    return (
        "Чтобы рассчитать скидку по действующей политике, подскажите, пожалуйста, "
        "какую модель и в каком количестве вы планируете заказать."
    )


def ask_people_count() -> str:
    """Для КП нужно число сотрудников."""
    return "С удовольствием подготовлю комплект. Для скольких человек он нужен?"


def will_clarify_and_return() -> str:
    """Категория E при неуверенности: «уточню и вернусь» (без обещаний по срокам)."""
    return "Хороший вопрос — уточню у специалиста и вернусь с ответом."


def hold_update(sla: SlaInfo) -> str:
    """Клиент пишет, пока диалог ждёт менеджера (Ст. 6: не оставлять без ответа)."""
    return (
        "Спасибо, я добавил ваше сообщение к обращению — менеджер увидит его сразу. "
        f"{sla_phrase(sla)}"
    )


def generic_fallback() -> str:
    """Уточняющий вопрос: низкая уверенность или провал валидации ответа."""
    return (
        "Спасибо за обращение! Мне нужно уточнить детали, чтобы дать точный ответ. "
        "Подскажите, пожалуйста, что именно вас интересует: товар, заказ, доставка или гарантия?"
    )
